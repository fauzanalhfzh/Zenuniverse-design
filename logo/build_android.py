"""Builds a drop-in Android res/ folder for Zeuniverse from the logo kit SVG masters.

Usage: python build_android.py [kit_dir] [out_dir]
Run build_kit.py first. Needs Chrome (via the logo-design render_png.py) for the PNG mipmaps.
"""
import os, re, shutil, subprocess, sys, tempfile
import xml.etree.ElementTree as ET

KIT = sys.argv[1] if len(sys.argv) > 1 else "kit"
OUT = sys.argv[2] if len(sys.argv) > 2 else "android"
RES = f"{OUT}/res"
RENDER = os.path.expanduser(
    "~/.claude/plugins/cache/logo-design-skill/logo-design/1.4.5/skills/logo-design/scripts/render_png.py")
SVG_NS = "{http://www.w3.org/2000/svg}"
ANDROID = "http://schemas.android.com/apk/res/android"

ORANGE, ORANGE_D, SKIN, NAVY = "#F5822A", "#D9661C", "#FCD3A6", "#2B2862"


def f(v):
    return f"{v:.3f}".rstrip("0").rstrip(".")


# ---------------------------------------------------------------- SVG -> VectorDrawable
def shape_to_path(el):
    tag = el.tag.replace(SVG_NS, "")
    g = lambda k, d=0.0: float(el.get(k, d))
    if tag == "path":
        return el.get("d")
    if tag in ("circle", "ellipse"):
        cx, cy = g("cx"), g("cy")
        rx = g("r") if tag == "circle" else g("rx")
        ry = g("r") if tag == "circle" else g("ry")
        return (f"M{f(cx-rx)},{f(cy)} A{f(rx)},{f(ry)} 0 1 0 {f(cx+rx)},{f(cy)} "
                f"A{f(rx)},{f(ry)} 0 1 0 {f(cx-rx)},{f(cy)} Z")
    if tag == "rect":
        x, y, w, h, r = g("x"), g("y"), g("width"), g("height"), g("rx")
        if not r:
            return f"M{f(x)},{f(y)} H{f(x+w)} V{f(y+h)} H{f(x)} Z"
        return (f"M{f(x+r)},{f(y)} H{f(x+w-r)} A{f(r)},{f(r)} 0 0 1 {f(x+w)},{f(y+r)} "
                f"V{f(y+h-r)} A{f(r)},{f(r)} 0 0 1 {f(x+w-r)},{f(y+h)} H{f(x+r)} "
                f"A{f(r)},{f(r)} 0 0 1 {f(x)},{f(y+h-r)} V{f(y+r)} A{f(r)},{f(r)} 0 0 1 {f(x+r)},{f(y)} Z")
    return None


def transform_groups(t):
    """SVG transform list -> nested VectorDrawable group attributes (outermost first)."""
    out = []
    for fn, args in re.findall(r"(translate|scale)\(([^)]*)\)", t or ""):
        nums = [float(n) for n in re.split(r"[ ,]+", args.strip())]
        if fn == "translate":
            out.append({"translateX": f(nums[0]), "translateY": f(nums[1] if len(nums) > 1 else 0)})
        else:
            out.append({"scaleX": f(nums[0]), "scaleY": f(nums[1] if len(nums) > 1 else nums[0])})
    return out


def convert(el, inherited, color_override, depth):
    pad = "    " * depth
    fill = el.get("fill", inherited["fill"])
    rule = el.get("fill-rule", inherited["rule"])
    alpha = inherited["alpha"] * float(el.get("opacity", 1))
    tag = el.tag.replace(SVG_NS, "")
    if tag == "title":
        return ""
    if tag in ("g", "svg"):
        body = "".join(convert(c, {"fill": fill, "rule": rule, "alpha": alpha}, color_override,
                               depth + len(transform_groups(el.get("transform")))) for c in el)
        for i, attrs in reversed(list(enumerate(transform_groups(el.get("transform"))))):
            a = " ".join(f'android:{k}="{v}"' for k, v in attrs.items())
            p = "    " * (depth + i)
            body = f"{p}<group {a}>\n{body}{p}</group>\n"
        return body
    d = shape_to_path(el)
    if d is None or fill in (None, "none"):
        return ""
    color = color_override or fill
    extra = ""
    if alpha < 1:
        extra += f' android:fillAlpha="{f(alpha)}"'
    if rule == "evenodd":
        extra += ' android:fillType="evenOdd"'
    return f'{pad}<path android:fillColor="{color}"{extra}\n{pad}    android:pathData="{" ".join(d.split())}"/>\n'


def vector(src, dst, width_dp, height_dp=None, viewport=None, place=None, color=None):
    """Write a VectorDrawable.

    viewport: (w, h) in viewport units; defaults to the SVG viewBox size.
    place:    (scale, tx, ty) maps SVG coordinates into the viewport: v = scale * svg + t.
    color:    force every fill to one colour (for system-tinted glyphs).
    """
    root = ET.parse(src).getroot()
    vx, vy, vw, vh = (float(n) for n in root.get("viewBox").split())
    if viewport is None:
        viewport = (vw, vh)
    if height_dp is None:
        height_dp = width_dp * viewport[1] / viewport[0]
    body = "".join(convert(c, {"fill": "#000000", "rule": "nonzero", "alpha": 1.0}, color, 2) for c in root)
    if place:
        k, tx, ty = place
        body = (f'    <group android:scaleX="{f(k)}" android:scaleY="{f(k)}" '
                f'android:translateX="{f(tx)}" android:translateY="{f(ty)}">\n{body}    </group>\n')
    elif vx or vy:
        body = (f'    <group android:translateX="{f(-vx)}" android:translateY="{f(-vy)}">\n{body}    </group>\n')
    xml = (f'<?xml version="1.0" encoding="utf-8"?>\n'
           f'<!-- Generated by logo/build_android.py from {os.path.basename(src)}; do not edit by hand. -->\n'
           f'<vector xmlns:android="{ANDROID}"\n'
           f'    android:width="{f(width_dp)}dp"\n    android:height="{f(height_dp)}dp"\n'
           f'    android:viewportWidth="{f(viewport[0])}"\n    android:viewportHeight="{f(viewport[1])}">\n'
           f'{body}</vector>\n')
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(dst, "w", encoding="utf-8") as fh:
        fh.write(xml)


def fit(viewport, centre_svg, radius_svg, radius_vp):
    """Scale + offset that puts an SVG circle (centre, radius) at the viewport centre with radius_vp."""
    k = radius_vp / radius_svg
    return k, viewport / 2 - k * centre_svg[0], viewport / 2 - k * centre_svg[1]


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


def render(src, dst, size):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    subprocess.run([sys.executable, RENDER, src, "-o", dst, "--size", str(size)], check=True,
                   stdout=subprocess.DEVNULL)


M = f"{KIT}/master"
FACE = f"{M}/zeuniverse-face.svg"
GLYPH = f"{M}/zeuniverse-glyph.svg"
# Face (tuft + mask) sits in a circle of radius ~110 around (128, 120); the glyph's ears reach ~125 from (128, 130).
FACE_C, FACE_R = (128, 120), 110
GLYPH_C, GLYPH_R = (128, 130), 125

# ---------------------------------------------------------------- adaptive launcher icon (API 26+)
# 108 dp canvas; launchers show the middle 72 dp and only a 66 dp circle is guaranteed.
vector(FACE, f"{RES}/drawable/ic_launcher_foreground.xml", 108, viewport=(108, 108),
       place=fit(108, FACE_C, FACE_R, 33))
vector(GLYPH, f"{RES}/drawable/ic_launcher_monochrome.xml", 108, viewport=(108, 108),
       place=fit(108, GLYPH_C, GLYPH_R, 33), color="#FFFFFFFF")
adaptive = (f'<?xml version="1.0" encoding="utf-8"?>\n'
            f'<adaptive-icon xmlns:android="{ANDROID}">\n'
            f'    <background android:drawable="@color/ic_launcher_background"/>\n'
            f'    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
            f'    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n'
            f'</adaptive-icon>\n')
write(f"{RES}/mipmap-anydpi-v26/ic_launcher.xml", adaptive)
write(f"{RES}/mipmap-anydpi-v26/ic_launcher_round.xml", adaptive)
write(f"{RES}/values/ic_launcher_background.xml",
      f'<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
      f'    <color name="ic_launcher_background">{ORANGE}</color>\n</resources>\n')

# ---------------------------------------------------------------- status-bar notification icon (white on transparent)
vector(GLYPH, f"{RES}/drawable/ic_stat_zeuniverse.xml", 24, viewport=(24, 24),
       place=fit(24, GLYPH_C, GLYPH_R, 11), color="#FFFFFFFF")

# ---------------------------------------------------------------- splash screen icon (Android 12 SplashScreen API)
# no icon background: 288 dp canvas, content must fit a 192 dp circle
vector(FACE, f"{RES}/drawable/splash_icon.xml", 288, viewport=(288, 288),
       place=fit(288, FACE_C, FACE_R, 96))

# ---------------------------------------------------------------- in-app logos and Otan expressions
for name, src, w in (
    ("zeuniverse_icon", "zeuniverse-icon.svg", 48),
    ("zeuniverse_icon_small", "zeuniverse-icon-small.svg", 24),
    ("zeuniverse_head", "zeuniverse-head.svg", 48),
    ("zeuniverse_icon_mono", "zeuniverse-icon-mono.svg", 48),
):
    vector(f"{M}/{src}", f"{RES}/drawable/{name}.xml", w)
for name, src in (
    ("zeuniverse_horizontal", "zeuniverse-horizontal.svg"),
    ("zeuniverse_horizontal_white", "zeuniverse-horizontal-white.svg"),
    ("zeuniverse_stacked", "zeuniverse-stacked.svg"),
    ("zeuniverse_stacked_white", "zeuniverse-stacked-white.svg"),
    ("zeuniverse_wordmark", "zeuniverse-wordmark.svg"),
    ("zeuniverse_wordmark_white", "zeuniverse-wordmark-white.svg"),
):
    vb = [float(n) for n in ET.parse(f"{M}/{src}").getroot().get("viewBox").split()]
    height = 40 if "stacked" not in name else 120
    vector(f"{M}/{src}", f"{RES}/drawable/{name}.xml", height * vb[2] / vb[3], height)
for expr in ("default", "happy", "wink", "wow", "astronaut"):
    vector(f"{KIT}/expressions/otan-{expr}.svg", f"{RES}/drawable/otan_{expr}.xml", 96)

write(f"{RES}/values/zeuniverse_colors.xml",
      f'<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
      f'    <color name="zeuniverse_orange">{ORANGE}</color>\n'
      f'    <color name="zeuniverse_fur_shade">{ORANGE_D}</color>\n'
      f'    <color name="zeuniverse_peach">{SKIN}</color>\n'
      f'    <color name="zeuniverse_navy">{NAVY}</color>\n</resources>\n')

# ---------------------------------------------------------------- legacy PNG mipmaps (API < 26) and Play Store icon
build = tempfile.mkdtemp(prefix="zeuniverse-android-")
face_body = "".join(ET.tostring(c, encoding="unicode") for c in ET.parse(FACE).getroot()
                    if c.tag != f"{SVG_NS}title").replace(' xmlns:ns0="http://www.w3.org/2000/svg"', "")
face_body = re.sub(r"</?ns0:", lambda m: m.group(0).replace("ns0:", ""), face_body)
k, tx, ty = fit(256, FACE_C, FACE_R, 112)
write(f"{build}/round.svg",
      f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256"><circle cx="128" cy="128" r="128" fill="{ORANGE}"/>'
      f'<g transform="translate({f(tx)} {f(ty)}) scale({f(k)})">{face_body}</g></svg>\n')
for density, px in (("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)):
    render(f"{M}/zeuniverse-icon.svg", f"{RES}/mipmap-{density}/ic_launcher.png", px)
    render(f"{build}/round.svg", f"{RES}/mipmap-{density}/ic_launcher_round.png", px)
# Play Store: full square, Google applies the corner mask itself
render(f"{M}/zeuniverse-icon-fullbleed.svg", f"{OUT}/playstore/ic_launcher-playstore.png", 512)
shutil.rmtree(build, ignore_errors=True)
print(f"android resources written to {RES}")
